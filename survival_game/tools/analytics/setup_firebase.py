#!/usr/bin/env python3
"""Create/reuse Lost Canopy Firebase on 3pgabor@gmail.com; capture all auth output."""
import argparse
import json
import os
from pathlib import Path
import plistlib
import re
import subprocess
import tempfile
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
ACCOUNT = '3pgabor@gmail.com'
PROJECT = 'lost-canopy-3pgabor'
IOS_BUNDLE = 'com.palgabor.lostcanopy'
ANDROID_PACKAGE = 'com.example.survival_game'


def cli(*args):
    # CLI authentication responses may contain tokens: never forward raw output.
    with tempfile.TemporaryDirectory(prefix='lost-canopy-firebase-') as directory:
        os.chmod(directory, 0o700)
        response = subprocess.run(['firebase', *args, '--account', ACCOUNT,
            '--non-interactive', '--json'], cwd=directory,
            capture_output=True, text=True, timeout=120,
            env={**os.environ, 'CI': 'true', 'NO_UPDATE_NOTIFIER': '1',
                 'FIREBASE_CLI_DISABLE_USAGE_REPORTING': 'true'})
    try:
        payload = json.loads(response.stdout)
    except json.JSONDecodeError:
        raise RuntimeError('Unusable CLI response') from None
    if response.returncode or payload.get('status') != 'success':
        raise RuntimeError(f'Firebase {args[0]} failed')
    return payload.get('result')


def options(platform, contents):
    if platform == 'ios':
        p = plistlib.loads(contents.encode())
        return dict(apiKey=p['API_KEY'], appId=p['GOOGLE_APP_ID'],
            messagingSenderId=p['GCM_SENDER_ID'], projectId=p['PROJECT_ID'],
            iosBundleId=p['BUNDLE_ID'], storageBucket=p.get('STORAGE_BUCKET'))
    p = json.loads(contents)
    client = next(c for c in p['client']
        if c['client_info']['android_client_info']['package_name'] == ANDROID_PACKAGE)
    return dict(apiKey=client['api_key'][0]['current_key'],
        appId=client['client_info']['mobilesdk_app_id'],
        messagingSenderId=p['project_info']['project_number'],
        projectId=p['project_info']['project_id'],
        storageBucket=p['project_info'].get('storage_bucket'))


def setup(project):
    result = cli('projects:list')
    projects = result.get('projects', []) if isinstance(result, dict) else result
    if not any(p.get('projectId') == project for p in projects):
        cli('projects:create', project, '--display-name', 'Lost Canopy')
        print(f'Created {project} under {ACCOUNT}.')
    else:
        print(f'Using {project} under {ACCOUNT}.')
    config = {'configured': True, 'project_id': project}
    apps = cli('apps:list', '--project', project)
    for platform, field, identifier, flag in [
        ('ios', 'bundleId', IOS_BUNDLE, '--bundle-id'),
        ('android', 'packageName', ANDROID_PACKAGE, '--package-name'),
    ]:
        match = next((app for app in apps if app.get(field) == identifier), None)
        if match is None:
            match = cli('apps:create', platform, f'Lost Canopy {platform}',
                flag, identifier, '--project', project)
        sdk = cli('apps:sdkconfig', platform, match['appId'], '--project', project)
        config[platform] = options(platform, sdk['fileContents'])
        if config[platform]['projectId'] != project:
            raise RuntimeError('SDK project mismatch')
        print(f'Registered {platform}: {identifier}.')
    path = ROOT / 'assets/config/firebase.json'
    temporary = path.with_suffix('.json.tmp')
    temporary.write_text(json.dumps(config, indent=2) + '\n')
    temporary.replace(path)
    # Equivalent to the public Android resources generated by google-services:
    # Analytics reads google_app_id as well as the initialized Firebase app.
    android = config['android']
    resources = {'google_app_id': android['appId'],
        'gcm_defaultSenderId': android['messagingSenderId'],
        'google_api_key': android['apiKey'], 'project_id': android['projectId']}
    resource_path = ROOT / 'android/app/src/main/res/values/firebase_options.xml'
    resource_path.parent.mkdir(parents=True, exist_ok=True)
    resource_path.write_text('<resources>\n' + ''.join(
        f'  <string name="{key}" translatable="false">{escape(str(value))}</string>\n'
        for key, value in resources.items()) + '</resources>\n')
    print('Public SDK configuration saved in assets/config/firebase.json.')
    print(f'Enable Google Analytics, then link BigQuery: https://console.firebase.google.com/project/{project}/settings/integrations')
    print('No billing, hosting or database enabled by this script.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', default=PROJECT)
    args = parser.parse_args()
    if not re.fullmatch(r'[a-z][a-z0-9-]{4,28}[a-z0-9]', args.project):
        parser.error('Invalid Google Cloud project ID')
    try:
        setup(args.project)
    except (RuntimeError, subprocess.SubprocessError, OSError, KeyError, ValueError):
        print('Setup incomplete. Check Firebase CLI login, Google API access and project permissions. No raw auth response displayed.')
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
